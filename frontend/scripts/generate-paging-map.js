/**
 * Generates `src/api/generated/paging.ts` — which list endpoints page on the server, and what they
 * can be sorted by — from the committed OpenAPI spec.
 *
 * This exists so that the switch from client-side to server-side paging is a regeneration rather
 * than a component rewrite. Today 3 of 56 list endpoints page on the server; the rest return
 * everything and `DataTable` pages them in the browser. When tier-A paging lands on inventory lots
 * or the email outbox, `npm run api:generate` moves those endpoints across and no screen changes.
 *
 * Reading it from the spec rather than maintaining a list by hand is the whole point: a hand-kept
 * list is a second source of truth, and the failure mode is a table that quietly pages the first
 * 20 rows of a 4,000-row result and looks entirely correct.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SPEC = resolve(here, '../../docs/api/openapi.json')
const OUTPUT = resolve(here, '../src/api/generated/paging.ts')

const HTTP_VERBS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options']

const spec = JSON.parse(readFileSync(SPEC, 'utf8'))

/** Resolves a `$ref` into the schema it names. Only local component refs exist in this spec. */
function deref(schema) {
  if (!schema) return undefined
  const ref = schema.$ref
  if (!ref) return schema
  const name = ref.replace('#/components/schemas/', '')
  return spec.components?.schemas?.[name]
}

function listItemType(operation) {
  const schema = operation.responses?.['200']?.content?.['application/json']?.schema
  const ref = schema?.$ref ?? ''
  if (!ref.includes('ListResponse_')) return undefined
  return ref.replace('#/components/schemas/ListResponse_', '')
}

const entries = []

for (const [path, verbs] of Object.entries(spec.paths ?? {})) {
  for (const [verb, operation] of Object.entries(verbs ?? {})) {
    if (!HTTP_VERBS.includes(verb)) continue

    const itemType = listItemType(operation)
    if (!itemType) continue

    const parameters = operation.parameters ?? []
    const names = parameters.map((parameter) => parameter.name)
    const paged = names.includes('page') && names.includes('size')

    const sortParameter = parameters.find((parameter) => parameter.name === 'sort')
    const sorts = deref(sortParameter?.schema)?.enum ?? []

    entries.push({
      route: `${verb.toUpperCase()} ${path}`,
      itemType,
      paged,
      sorts,
    })
  }
}

entries.sort((a, b) => a.route.localeCompare(b.route))

const pagedCount = entries.filter((entry) => entry.paged).length

const body = entries
  .map(
    (entry) =>
      `  '${entry.route}': { paged: ${entry.paged}, sorts: [${entry.sorts
        .map((sort) => `'${sort}'`)
        .join(', ')}] },`,
  )
  .join('\n')

const output = `/**
 * Generated by scripts/generate-paging-map.js from docs/api/openapi.json.
 * Do not edit manually — run \`npm run api:generate\`.
 *
 * ${entries.length} list endpoints, of which ${pagedCount} page on the server today.
 * An endpoint gains server-side paging here the moment the backend gives it page/size
 * parameters, and every table over it follows without being touched.
 */

/** What a list endpoint can do, as its own description of itself says. */
export interface PagingCapability {
  /** True when the endpoint accepts \`page\` and \`size\`, so the server does the paging. */
  readonly paged: boolean
  /** Values its \`sort\` parameter accepts. Empty when it does not sort on the server. */
  readonly sorts: readonly string[]
}

/** Keyed by \`METHOD /path\` exactly as the route appears in the spec. */
export const PAGING_CAPABILITIES = {
${body}
} as const satisfies Record<string, PagingCapability>

export type PagedRoute = keyof typeof PAGING_CAPABILITIES

/**
 * How a table over this route should page.
 *
 * An unknown route is client-paged rather than a thrown error: a table with no capability entry is
 * a table over something that is not a \`ListResponse\`, and refusing to render it would be a worse
 * answer than paging its rows in the browser.
 */
export function pagingCapability(route: string): PagingCapability {
  return (PAGING_CAPABILITIES as Record<string, PagingCapability>)[route] ?? { paged: false, sorts: [] }
}
`

mkdirSync(dirname(OUTPUT), { recursive: true })
writeFileSync(OUTPUT, output, 'utf8')

console.log(
  `paging map: ${entries.length} list endpoints, ${pagedCount} server-paged → src/api/generated/paging.ts`,
)
